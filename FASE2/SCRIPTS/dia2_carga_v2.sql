-- ------------------------------------------------------------
-- VALIDACION DIA 2
-- ------------------------------------------------------------
SELECT 'PARTIDO'           AS TABLA, COUNT(*) AS TOTAL FROM PARTIDO WHERE ANIO = 2030
UNION ALL SELECT 'GOL',              COUNT(*) FROM GOL WHERE ID_PARTIDO BETWEEN 2001 AND 2020
UNION ALL SELECT 'POSICION_GRUPO',   COUNT(*) FROM POSICION_GRUPO WHERE ANIO = 2030
UNION ALL SELECT 'GOLEADOR',         COUNT(*) FROM GOLEADOR WHERE ANIO = 2030
UNION ALL SELECT 'TARJETA',          COUNT(*) FROM TARJETA WHERE ANIO = 2030
UNION ALL SELECT 'JUGADOR_PAIS',     COUNT(*) FROM JUGADOR_PAIS WHERE ID_JUGADOR BETWEEN 9001 AND 9026
UNION ALL SELECT 'LOG_PARTIDO',      COUNT(*) FROM LOG_PARTIDO
UNION ALL SELECT 'LOG_GOL',          COUNT(*) FROM LOG_GOL
UNION ALL SELECT 'LOG_POSICION_GRUPO', COUNT(*) FROM LOG_POSICION_GRUPO
UNION ALL SELECT 'LOG_GOLEADOR',     COUNT(*) FROM LOG_GOLEADOR
UNION ALL SELECT 'LOG_TARJETA',      COUNT(*) FROM LOG_TARJETA;
