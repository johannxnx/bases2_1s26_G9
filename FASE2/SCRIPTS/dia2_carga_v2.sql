            v_cnt, 0, 'Carga dia 2 - Jornada 2 + Cuartos - ' || v_cnt || ' partidos acumulados');

    SELECT COUNT(*) INTO v_cnt FROM GOL WHERE ID_PARTIDO BETWEEN 2001 AND 2020;
    INSERT INTO LOG_GOL (ID_LOG, FECHA_REGISTRO, OPERACION,
                          CANTIDAD_REGISTROS, FRAGMENTACION_PORCENT, DESCRIPCION)
