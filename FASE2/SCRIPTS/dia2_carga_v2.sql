            v_cnt, 0, 'Carga dia 2 - Goles acumulados - ' || v_cnt || ' registros');

    SELECT COUNT(*) INTO v_cnt FROM POSICION_GRUPO WHERE ANIO = 2030;
    INSERT INTO LOG_POSICION_GRUPO (ID_LOG, FECHA_REGISTRO, OPERACION,
                                     CANTIDAD_REGISTROS, FRAGMENTACION_PORCENT, DESCRIPCION)
